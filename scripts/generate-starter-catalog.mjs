import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve, relative, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
import { createServer as createHttpServer } from "node:http";

// Snapshot data stays in the authored fixtures. This small generated index is
// the only fixture metadata that browsing/searching the gallery downloads.
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fixtures = resolve(root, "src/visual-engine/fixtures");
const target = resolve(root, "src/visual-engine/templates/starterCatalog.generated.ts");
const server = await createServer({ root, configFile: false, server: { middlewareMode: true, hmr: { server: createHttpServer() } }, optimizeDeps: { noDiscovery: true, include: [] }, appType: "custom" });
try {
  const { ALL_CURATED_STARTERS: starters } = await server.ssrLoadModule("/src/visual-engine/fixtures/templateStarters.ts");
  const files = (await readdir(fixtures, { recursive: true })).filter(file => file.endsWith(".ts") && !file.endsWith("index.ts") && !file.includes(".test.") && file !== "templateStarters.ts").sort();
  const locations = new Map();
  for (const file of files) {
    const exports = await server.ssrLoadModule(`/src/visual-engine/fixtures/${file}`);
    const source = `../fixtures/${file.slice(0, -3)}`;
    for (const [name, value] of Object.entries(exports)) {
      const docs = Array.isArray(value) ? value : [value];
      for (let index = 0; index < docs.length; index++) {
        const doc = docs[index];
        if (starters.includes(doc) && !locations.has(doc)) locations.set(doc, { source, exportName: name, index: Array.isArray(value) ? index : null });
      }
    }
  }
  const sources = [...new Set(starters.map(doc => {
    if (!locations.has(doc)) throw new Error(`No fixture export for ${doc.id}`);
    return locations.get(doc).source;
  }))].sort();
  const entries = starters.map(doc => ({ id: doc.id, name: doc.name, kind: doc.kind, tags: doc.tags, ...locations.get(doc), source: sources.indexOf(locations.get(doc).source) }));
  const output = `// Generated by scripts/generate-starter-catalog.mjs. Do not edit.\nexport const starterModules: (() => Promise<Record<string, unknown>>)[] = [\n${sources.map(source => `  () => import(${JSON.stringify(source)}),`).join("\n")}\n];\n\nexport const starterEntries = ${JSON.stringify(entries, null, 2)};\n`;
  if (process.argv.includes("--check")) {
    if (await readFile(target, "utf8") !== output) throw new Error("Starter catalog is stale; run yarn templates:catalog");
  } else await writeFile(target, output);
  process.stdout.write(`Starter catalog: ${entries.length} entries, ${sources.length} lazy fixture modules (${relative(root, target)}).\n`);
} finally { await server.close(); }
